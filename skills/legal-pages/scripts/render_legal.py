#!/usr/bin/env python3
"""Render privacy / terms / refund pages from legal-config.json. Standard library only.

Usage:
  python3 render_legal.py --config legal-config.json --out DIR [--format md|html|nextjs]
                          [--only privacy,terms,refund] [--templates DIR]

NOT LEGAL ADVICE: output is a template the site owner must review (ideally with a lawyer).
Exit code: 0 ok, 1 config error. Remaining [[TODO]] markers are listed on stderr.
"""
import argparse
import datetime as dt
import html
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TEMPLATES = os.path.join(HERE, "..", "assets", "templates")
DOCS = {"privacy": "Privacy Policy", "terms": "Terms of Service", "refund": "Refund Policy"}
REQUIRED = ["company_name", "product_name", "website_url", "contact_email", "merchant_of_record",
            "refund_mode", "governing_law", "address", "legal_entity_type"]
MOR = {
    "creem": {"mor_name": "Creem", "mor_url": "https://www.creem.io",
              "mor_privacy_url": "https://www.creem.io/privacy", "mor_terms_url": "https://www.creem.io/buyer-terms"},
    "paddle": {"mor_name": "Paddle.com", "mor_url": "https://www.paddle.com",
               "mor_privacy_url": "https://www.paddle.com/legal/privacy",
               "mor_terms_url": "https://www.paddle.com/legal/checkout-buyer-terms"},
    "lemonsqueezy": {"mor_name": "Lemon Squeezy", "mor_url": "https://www.lemonsqueezy.com",
                     "mor_privacy_url": "https://www.lemonsqueezy.com/privacy",
                     "mor_terms_url": "https://www.lemonsqueezy.com/buyer-terms"},
}
REVIEW_NOTICE = ("Template generated by the legal-pages skill. Not legal advice. "
                 "Review every section and have it checked by a qualified lawyer before relying on it.")

SECTION = re.compile(r"\{\{([#^])\s*([\w.]+)\s*\}\}\n?(.*?)\{\{/\s*\2\s*\}\}\n?", re.S)
VAR = re.compile(r"\{\{\s*([\w.]+)\s*\}\}")


def lookup(ctx_stack, key):
    if key == ".":
        return ctx_stack[-1]
    for ctx in reversed(ctx_stack):
        if isinstance(ctx, dict) and key in ctx:
            return ctx[key]
    return None


def render(tpl, ctx_stack, missing):
    def section(m):
        kind, key, body = m.group(1), m.group(2), m.group(3)
        val = lookup(ctx_stack, key)
        if kind == "^":
            return render(body, ctx_stack, missing) if not val else ""
        if not val:
            return ""
        if isinstance(val, list):
            return "".join(render(body, ctx_stack + [item], missing) for item in val)
        if isinstance(val, dict):
            return render(body, ctx_stack + [val], missing)
        return render(body, ctx_stack, missing)

    prev = None
    while prev != tpl:  # resolve outer sections (inner ones handled recursively)
        prev = tpl
        tpl = SECTION.sub(section, tpl, count=1)

    def var(m):
        val = lookup(ctx_stack, m.group(1))
        if val is None or val == "":
            missing.add(m.group(1))
            return f"[[TODO: {m.group(1)}]]"
        return str(val)

    return VAR.sub(var, tpl)


def md_inline(s):
    s = html.escape(s, quote=False)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"(?<![\w*])_(.+?)_(?![\w*])", r"<em>\1</em>", s)
    s = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', s)
    s = re.sub(r"(?<![\"'>=])(https?://[^\s<)]+[^\s<).,])", r'<a href="\1">\1</a>', s)
    s = re.sub(r"\[\[(TODO:[^\]]*)\]\]", r'<mark class="legal-todo">[[\1]]</mark>', s)
    return s


def md_to_html(md):
    out, para, in_list = [], [], False

    def flush():
        nonlocal para
        if para:
            out.append("<p>" + md_inline(" ".join(para)) + "</p>")
            para = []

    for line in md.splitlines():
        st = line.strip()
        if not st:
            flush()
            if in_list:
                out.append("</ul>")
                in_list = False
            continue
        h = re.match(r"(#{1,4})\s+(.*)", st)
        if h:
            flush()
            if in_list:
                out.append("</ul>")
                in_list = False
            n = len(h.group(1))
            out.append(f"<h{n}>{md_inline(h.group(2))}</h{n}>")
        elif st.startswith("- "):
            flush()
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append("<li>" + md_inline(st[2:]) + "</li>")
        else:
            para.append(st)
    flush()
    if in_list:
        out.append("</ul>")
    return "\n".join(out)


def tidy(md):
    md = re.sub(r"([^\n])\n(#{1,4} )", r"\1\n\n\2", md)  # blank line before headings
    md = re.sub(r"\n{3,}", "\n\n", md)
    return md.strip() + "\n"


def build_context(cfg):
    ctx = dict(cfg)
    mor_key = (cfg.get("merchant_of_record") or "none").lower()
    if mor_key in MOR:
        ctx.update(MOR[mor_key])
        ctx["mor"] = True
    elif mor_key in ("none", "stripe", "direct", ""):
        ctx["mor"] = False
    else:
        raise ValueError(f"merchant_of_record must be one of {sorted(MOR)} or none/stripe, got {mor_key!r}")
    mode = cfg.get("refund_mode")
    if mode not in ("window", "case_by_case", "none"):
        raise ValueError("refund_mode must be window, case_by_case or none")
    ctx["refund_window"] = mode == "window"
    ctx["refund_case_by_case"] = mode == "case_by_case"
    ctx["refund_none"] = mode == "none"
    if mode == "window" and not cfg.get("refund_window_days"):
        raise ValueError("refund_mode=window needs refund_window_days")
    ctx["effective_date"] = cfg.get("effective_date") or dt.date.today().isoformat()
    ctx["website_url"] = cfg["website_url"].rstrip("/")
    ctx.setdefault("min_age", 16)
    ctx.setdefault("retention_days_logs", 90)
    return ctx


NEXT_PAGE = '''// Generated by the legal-pages skill on {date}. {notice}
// Re-generate with: python3 render_legal.py --config legal-config.json --format nextjs
import type {{ Metadata }} from "next";

export const metadata: Metadata = {{ title: {title}, alternates: {{ canonical: "/{slug}" }} }};

const html = {html};

export default function Page() {{
  return (
    <main className="legal-page mx-auto max-w-3xl px-6 py-12 prose">
      <div dangerouslySetInnerHTML={{{{ __html: html }}}} />
    </main>
  );
}}
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--format", choices=["md", "html", "nextjs"], default="md")
    ap.add_argument("--only", default="privacy,terms,refund")
    ap.add_argument("--templates", default=DEFAULT_TEMPLATES)
    a = ap.parse_args()

    with open(a.config, encoding="utf-8") as f:
        cfg = json.load(f)
    absent = [k for k in REQUIRED if not cfg.get(k)]
    if absent:
        print(f"config is missing required fields: {', '.join(absent)}\n"
              "(use a [[TODO: ...]] value if the user has not decided yet)", file=sys.stderr)
        return 1
    try:
        ctx = build_context(cfg)
    except ValueError as e:
        print(f"config error: {e}", file=sys.stderr)
        return 1

    todos_all = {}
    for slug in [s.strip() for s in a.only.split(",") if s.strip()]:
        if slug not in DOCS:
            print(f"unknown document {slug!r}", file=sys.stderr)
            return 1
        with open(os.path.join(a.templates, f"{slug}.md"), encoding="utf-8") as f:
            tpl = f.read()
        missing = set()
        md = tidy(render(tpl, [ctx], missing))
        todos = sorted(set(re.findall(r"\[\[TODO:\s*([^\]]+)\]\]", md)))
        todos_all[slug] = todos
        if a.format == "md":
            path = os.path.join(a.out, f"{slug}.md")
            content = f"<!-- {REVIEW_NOTICE} -->\n\n{md}"
        elif a.format == "html":
            path = os.path.join(a.out, f"{slug}.html")
            content = (f"<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
                       f"<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
                       f"<title>{DOCS[slug]} | {html.escape(ctx['product_name'])}</title></head>\n"
                       f"<body><!-- {REVIEW_NOTICE} -->\n<main>\n{md_to_html(md)}\n</main></body></html>\n")
        else:
            path = os.path.join(a.out, slug, "page.tsx")
            content = NEXT_PAGE.format(date=dt.date.today().isoformat(), notice=REVIEW_NOTICE,
                                       title=json.dumps(DOCS[slug]), slug=slug,
                                       html=json.dumps(md_to_html(md), ensure_ascii=False))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"wrote {path}")

    print("\nNOT LEGAL ADVICE - review the text and have a qualified lawyer check it.", file=sys.stderr)
    open_items = [(s, t) for s, ts in todos_all.items() for t in ts]
    if open_items:
        print(f"{len(open_items)} open [[TODO]] item(s):", file=sys.stderr)
        for s, t in open_items:
            print(f"  - {s}: {t}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
